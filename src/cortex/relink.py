"""Obsidian graph links behind `cortex relink`, and the helpers new writes use.

Obsidian draws `[[links]]` from note bodies and `"[[x]]"` strings in properties, resolving them
by path or file name, case-insensitively. Cortex adds what its graph has but Obsidian's lacks:
an `Up: [[...]]` line (session -> journal day -> month page -> topic map, people page -> hub),
the generated people hub `notes/people.md` (public pages only, as index.md lists them), plain
frontmatter edges as `"[[id]]"` (the form `cortex_add` already writes), and a report of
unresolved links: near matches are rewritten, junk (code like `df[['a']]`) is escaped to
`\\[\\[...]]`, and slug-like targets are listed as missing notes. Every write goes through
`cortex.vault`.
"""

from __future__ import annotations

import re
from collections import Counter
from collections.abc import Callable
from pathlib import Path

from ruamel.yaml import YAMLError

from cortex.catalog import slugify
from cortex.index import EDGE_KEYS, _edge_targets, _target
from cortex.vault import (
    HEADING_RE,
    ID_RE,
    Note,
    Vault,
    VaultError,
    _dump_fm,
    _load_fm,
    _newline,
    _section,
    _split,
    _to_yaml,
    is_private,
    truthy,
)

TOPIC_MAP = "my-topic-map"  # the imported topic hub (notes/); month pages link it if it exists
HUB = "people"  # notes/people.md
DAY_RE = re.compile(r"^\d{4}-\d{2}-\d{2}")
LINK_RE = re.compile(r"\[\[([^\]\n]*)\]\]")
# a fenced block or inline code span (Obsidian draws no links there), else a [[link]]
TOKEN_RE = re.compile(r"(?P<code>^(?P<f>```|~~~).*?^(?P=f)[^\n]*$|`[^`\n]*`)"
                      r"|\[\[(?P<t>[^\]\n]*)\]\]", re.M | re.S)
EDGES = tuple(k for k in EDGE_KEYS if k != "tests")  # tests maps concept:x to weights


def _tgt(raw: str) -> str:
    """The link target: `[[x|alias]]`, `[[x#h]]` and `[[x^b]]` -> x."""
    return re.split(r"[|#^]", raw, maxsplit=1)[0].strip()


def _parts(text: str) -> tuple[str, str]:
    """(frontmatter with fences, body); ('', text) without frontmatter or when it is broken."""
    try:
        p = _split(text)
    except ValueError:
        return "", text
    return ("".join(p[:3]), p[3]) if p else ("", text)


def links(text: str) -> list[str]:
    """Raw link texts Obsidian sees: frontmatter, and the body outside code."""
    head, body = _parts(text)
    return LINK_RE.findall(head) + [m["t"] for m in TOKEN_RE.finditer(body) if m["t"] is not None]


def has_link(text: str, target: str) -> bool:
    t = target.lower()
    return any((x := _tgt(r).lower().removesuffix(".md")) == t or x.endswith("/" + t)
               for r in links(text))


def with_up(text: str, target: str, label: str = "Up") -> str:
    """`text` with a `label: [[target]]` line under its H1 (or atop the body), unless it
    already links `target`."""
    if has_link(text, target):
        return text
    head, body = _parts(text)
    nl = _newline(text) if text else "\n"
    lines = body.splitlines(keepends=True)
    at = 1 if lines and lines[0].startswith("# ") else 0
    if at and not lines[0].endswith("\n"):
        lines[0] += nl
    new = [nl] if at else []
    new.append(f"{label}: [[{target}]]{nl}")
    if at < len(lines) and lines[at].strip():
        new.append(nl)
    lines[at:at] = new
    return head + "".join(lines)


def journal_up(vault: Vault, day: str) -> str | None:
    """What journal page `day` links up to: its month page `YYYY-MM-01`, or for a month page
    the topic map; None when that page does not exist."""
    month = day[:8] + "01"
    if day != month:
        return month if vault.path_for("journal", month).is_file() else None
    return TOPIC_MAP if vault.path_for("note", TOPIC_MAP).is_file() else None


def hub_text(vault: Vault) -> str:
    """The people hub: a link per public people page; private pages are left out, as in
    index.md, so the hub never shows they exist."""
    from cortex.people import PREFIX  # lazy: people imports this module

    rows = [f"- [[{PREFIX}{n.id}]]" for n in vault.iter_notes("person") if not is_private(n)]
    return (f'---\nid: "{HUB}"\ntitle: "People"\nkind: "note"\nnote_type: "structure"\n'
            "tags: []\nrelated: []\n---\n# People\n\n"
            "Generated by Cortex from people/ (`cortex relink`); private pages are left out.\n"
            "\n## Pages\n" + ("\n".join(rows) or "- none") + "\n")


def with_row(text: str, heading: str, target: str, before=()) -> str:
    """`text` with `- [[target]]` at the end of its `## heading` section (made before the first
    `before` heading present, else at the end), unless it already links `target`."""
    if has_link(text, target):
        return text
    head, body = _parts(text)
    nl = _newline(text) if text else "\n"
    lines = body.splitlines(keepends=True)
    if lines and not lines[-1].endswith("\n"):
        lines[-1] += nl
    row = f"- [[{target}]]{nl}"
    try:
        _, e = _section(lines, heading)
        while not lines[e - 1].strip():
            e -= 1
        lines[e:e] = [row]
    except VaultError:
        at = next((i for i, ln in enumerate(lines) if (m := HEADING_RE.match(ln.rstrip("\r\n")))
                   and len(m.group(1)) == 2 and m.group(2) in before), len(lines))
        new = [f"## {heading}{nl}", row]
        if at < len(lines):
            new.append(nl)
        if at and lines[at - 1].strip():
            new.insert(0, nl)
        lines[at:at] = new
    return head + "".join(lines)


def _norm(s: str) -> str:
    return re.sub(r"[\s_-]+", " ", str(s).lower().replace("&", " and ")).strip()


def domain_hubs(fields: dict[str, dict]) -> list[tuple[str, str]]:
    """(domain id, hub id) pairs from public pages' frontmatter (`fields` maps
    'domain:<id>' / 'hub:<id>' to it). A pair needs a normalised name of the domain (id, title,
    alias) to equal a whole hub name: its title, an alias, or a trailing run of its id's
    segments after `topic-` of at least two segments or one of 5+ characters
    (`system-design` = `topic-software-system-design`; never `os` for `topic-x-cosmos`, nor
    `data` for `topic-x-data`).
    Of a matched hub and its matched sub-hubs only the most general is kept, shortest id
    first, at most three per domain."""
    def names(f: dict, id: str) -> set[str]:
        al = f.get("aliases")
        al = al if isinstance(al, list) else [al] if isinstance(al, str) else []
        return {n for x in (id, f.get("title") or "", *al) if (n := _norm(x))}

    hubs = {k[4:]: f for k, f in fields.items() if k.startswith("hub:")}
    hub_names = {}
    for h, f in hubs.items():
        segs = h.removeprefix("topic-").split("-")
        # a lone short segment (data, apis, ml, os) is too ambiguous to name a hub
        hub_names[h] = names(f, "") | {_norm("-".join(segs[i:])) for i in range(len(segs))
                                       if i < len(segs) - 1 or len(segs[i]) >= 5}
    parent = {h: next((t for t in _edge_targets(f.get("related") or []) if t in hubs and t != h),
                      None) for h, f in hubs.items()}

    def line(h: str) -> set[str]:  # h and its ancestors
        out = set()
        while h is not None and h not in out:
            out.add(h)
            h = parent[h]
        return out

    pairs = []
    for k, f in sorted(fields.items()):
        if not k.startswith("domain:"):
            continue
        d = k[7:]
        mine = names(f, d)
        kept: list[str] = []
        for h in sorted((h for h in hubs if hub_names[h] & mine), key=lambda h: (len(h), h)):
            if len(kept) < 3 and not any(x in line(h) or h in line(x) for x in kept):
                kept.append(h)
        pairs += [(d, h) for h in kept]
    return pairs


Fixes = dict[Path, list[tuple[str, Callable[[str], str]]]]


def people_fixes(vault: Vault) -> Fixes:
    """Hub, `People: [[people]]` on me/profile and `Up: [[people]]` on each people page;
    nothing until the first people page (a forgotten last page still empties the hub)."""
    pages = [p for p in sorted((vault.root / "people").glob("*.md")) if ID_RE.fullmatch(p.stem)]
    path = vault.path_for("note", HUB)
    if not pages and not path.is_file():
        return {}
    hub = hub_text(vault)
    out: Fixes = {path: [("people_hub", lambda _t: hub)]}
    for p in pages:
        out[p] = [("people_up", lambda t: with_up(t, HUB))]
    profile = vault.path_for("me", "profile")
    if profile.is_file():
        out[profile] = [("profile_hub", lambda t: with_up(t, HUB, "People"))]
    return out


def apply(vault: Vault, fixes: Fixes) -> Counter:
    """Write each fixed file through the vault (rereading under the lock); count changed files
    per fix kind."""
    done = Counter()
    with vault.lock():
        for path, fns in fixes.items():
            def change(text: str, fns=fns) -> str:
                for kind, fn in fns:
                    new = fn(text)
                    if new != text:
                        done[kind] += 1
                    text = new
                return text

            if path.is_file():
                vault._mutate(path, change)
            elif new := change(""):
                vault.write_text(path, new)
    return done


# ---- the whole-vault pass (`cortex relink`) -----------------------------------------------

_KIND_OF = {d: k for k, d in Vault.KIND_DIRS.items()}


def _hidden(root: Path, p: Path, text: str) -> bool:
    """A page whose links and path the report never names: browse/private/ and any page
    `is_private` calls private (people pages unless `private: false`)."""
    parts = p.relative_to(root).parts
    if parts[:2] == ("browse", "private"):
        return True
    try:
        sp = _split(text)
        f = _load_fm(sp[1]) if sp else {}
    except Exception:  # YAML errors are not ValueErrors; broken frontmatter may say private
        return True
    kind = _KIND_OF.get(parts[0]) if len(parts) == 2 else None
    return is_private(Note(p, kind, p.stem, f, ""))


def _pages(root: Path) -> list[Path]:
    return [p for p in root.rglob("*") if p.is_file()
            and not any(s.startswith(".") for s in p.relative_to(root).parts[:-1])]


class _Names:
    """Obsidian-style resolution over the vault's files (any extension)."""

    def __init__(self, root: Path, files: list[Path]):
        self.by_path: dict[str, str] = {}
        self.by_name: dict[str, str] = {}
        for p in sorted(files, key=lambda p: (len(p.relative_to(root).parts), str(p))):
            rel = p.relative_to(root).as_posix()
            keys = [rel.lower()]
            if p.suffix == ".md":
                keys.append(rel[:-3].lower())
            for k in keys:
                self.by_path.setdefault(k, rel)
                self.by_name.setdefault(k.rsplit("/", 1)[-1], rel)

    def resolve(self, target: str) -> str | None:
        t = target.replace("\\", "/").lower()
        if hit := self.by_path.get(t) or self.by_path.get(t + ".md"):
            return hit
        if "/" not in t:
            return self.by_name.get(t)
        return next((v for k, v in self.by_path.items() if k.endswith("/" + t)), None)


def classify(target: str, ids: set[str]) -> tuple[str, str | None]:
    """('near', id) for a note id the target misspells (case, slug, folder prefix);
    ('missing', None) for a slug-like id that should be a note; ('junk', None) otherwise."""
    base = target.replace("\\", "/").rsplit("/", 1)[-1].removesuffix(".md").strip().lower()
    for key in (base, re.sub(r"[^a-z0-9.]+", "-", base).strip("-"), slugify(base)):
        if key in ids:
            return "near", key
    if ID_RE.fullmatch(base) and "-" in base and not base.replace("-", "").isdigit():
        return "missing", None
    return "junk", None


def _rewrite(text: str, act: dict[str, tuple[str, str | None]], fixed: Counter) -> str:
    """Near-match links get the right id (frontmatter and body); junk is escaped (body only:
    a backslash is no valid escape inside a YAML string)."""
    head, body = _parts(text)

    def near(raw: str) -> str | None:
        a = act.get(_tgt(raw))
        return a[1] + raw[len(raw.split("|")[0].split("#")[0].split("^")[0]):] \
            if a and a[0] == "near" else None

    def fm(m: re.Match) -> str:
        new = near(m[1])
        if new is None:
            return m[0]
        fixed[_tgt(m[1])] += 1
        return f"[[{new}]]"

    def bd(m: re.Match) -> str:
        if m["t"] is None or not (a := act.get(_tgt(m["t"]))) or a[0] == "missing":
            return m[0]
        fixed[_tgt(m["t"])] += 1
        return f"[[{near(m['t'])}]]" if a[0] == "near" else f"\\[\\[{m['t']}]]"

    return LINK_RE.sub(fm, head) + TOKEN_RE.sub(bd, body)


def _fm_links(text: str, exists: Callable[[str], bool]) -> str:
    """Plain frontmatter edge ids (`related: [x]`) as `"[[x]]"` when note x exists."""
    try:
        parts = _split(text)
        if parts is None:
            return text
        head, fm, close, body = parts
        data = _load_fm(fm)
    except (ValueError, YAMLError):  # broken YAML: leave the page as it is
        return text
    changed = False
    for key in EDGES:
        v = data.get(key)
        items = list(v) if isinstance(v, list) else [v] if isinstance(v, str) else []
        new = [f"[[{t}]]" if isinstance(x, str) and not x.strip().startswith("[[")
               and (t := _target(x)) and exists(t) else x for x in items]
        if new != items:
            data[key] = _to_yaml(new if isinstance(v, list) else new[0])
            changed = True
    return head + _dump_fm(data, _newline(text)) + close + body if changed else text


def orphans(texts: dict[str, str], names: _Names) -> Counter:
    """Pages with no resolved [[link]] in or out, counted by top folder ('(root)' at the top)."""
    out, inbound = {}, Counter()
    for rel, text in texts.items():
        dst = {d for r in links(text) if (t := _tgt(r)) and (d := names.resolve(t))
               and d.endswith(".md") and d != rel}
        out[rel] = dst
        inbound.update(dst)
    return Counter(rel.split("/")[0] if "/" in rel else "(root)" for rel in texts
                   if not out[rel] and not inbound[rel])


def run(vault: Vault, dry_run: bool = True) -> dict:
    """Plan (and unless `dry_run`, write) every fix; returns orphans before and after, files
    changed per fix kind, the unresolved-link rows and the frontmatter edges converted."""
    root = vault.root
    files = _pages(root)
    md = [p for p in files if p.suffix == ".md"]
    texts = {p.relative_to(root).as_posix(): p.read_bytes().decode("utf-8", "replace")
             for p in md}
    names = _Names(root, files)
    kind_dirs = set(vault.KIND_DIRS.values())
    notes = [p for p in md if p.parent.parent == root and p.parent.name in kind_dirs
             and ID_RE.fullmatch(p.stem)]
    note_ids = {p.stem for p in notes}  # ids are unique across kinds (Vault.create_note)

    # unresolved links, by target; every page's links are fixed, but only public pages are
    # reported, so a private page's targets and path never reach the output
    seen: dict[str, dict] = {}
    targets: set[str] = set()
    for p in md:
        rel = p.relative_to(root).as_posix()
        text = texts[rel]
        hide = None
        for r in links(text):
            t = _tgt(r)
            if t and not names.resolve(t):
                targets.add(t)
                if hide is None:
                    hide = _hidden(root, p, text)
                if not hide:
                    row = seen.setdefault(t, {"target": t, "count": 0, "example": rel})
                    row["count"] += 1
    act = {t: classify(t, note_ids) for t in targets}

    fixes: Fixes = {}
    fixed = Counter()

    def add(p: Path, kind: str, fn) -> None:
        fixes.setdefault(p, []).append((kind, fn))

    for p in notes:
        kind_dir, day = p.parent.name, p.stem
        if kind_dir == "sessions" and DAY_RE.match(day) and \
                vault.path_for("journal", day[:10]).is_file():
            add(p, "session_up", lambda t, d=day[:10]: with_up(t, d))
        if kind_dir == "journal" and DAY_RE.fullmatch(day) and (up := journal_up(vault, day)):
            add(p, "journal_up", lambda t, u=up: with_up(t, u))
        if act:
            add(p, "links_fixed", lambda t: _rewrite(t, act, fixed))
        add(p, "frontmatter_links", lambda t: _fm_links(t, note_ids.__contains__))
    for p, fns in people_fixes(vault).items():
        fixes.setdefault(p, []).extend(fns)
    from cortex.topics import CONV, WATCHED  # lazy: topics imports this module

    fields = {}
    for p in notes:
        if p.parent.name not in ("domains", "notes") or p.stem == TOPIC_MAP:
            continue
        try:
            sp = _split(texts[p.relative_to(root).as_posix()])
            f = _load_fm(sp[1]) if sp else None
        except (ValueError, YAMLError):
            continue
        if f is None or truthy(f.get("private")):
            continue
        if p.parent.name == "domains":
            fields[f"domain:{p.stem}"] = f
        elif isinstance(f.get("tags"), list) and "topic" in f["tags"]:
            fields[f"hub:{p.stem}"] = f
    pairs = domain_hubs(fields)
    # the hub row sits outside the sections `topics.build` regenerates, so rebuilds keep it
    hub_heads = ("Sub-topics", "Subtopics", "Areas", *CONV, WATCHED)
    for d, h in pairs:
        add(vault.path_for("domain", d), "domain_topics", lambda t, h=h: with_row(t, "Topics", h))
        add(vault.path_for("note", h), "hub_domains",
            lambda t, d=d: with_row(t, "Study domains", d, before=hub_heads))

    after = dict(texts)  # predicted: every fix applied to the text read above
    counts = Counter()
    for p, fns in fixes.items():
        rel = p.relative_to(root).as_posix()
        text = texts.get(rel, "")
        for kind, fn in fns:
            new = fn(text)
            if new != text:
                counts[kind] += 1
            text = new
        if text:
            after[rel] = text
    if not dry_run:
        fixed.clear()
        counts = apply(vault, fixes)  # rereads each file under the lock
    rows = [{**row, "class": act[t][0], "to": act[t][1], "fixed": min(fixed[t], row["count"])}
            for t, row in sorted(seen.items(), key=lambda kv: (-kv[1]["count"], kv[0]))]
    hub = vault.path_for("note", HUB)
    new_files = files + [hub] if hub.relative_to(root).as_posix() in after else files
    return {"orphans_before": orphans(texts, names),
            "orphans_after": orphans(after, _Names(root, new_files)),
            "changed": counts, "unresolved": rows, "domain_hubs": pairs}


def report_lines(out: dict) -> list[str]:
    b, a = out["orphans_before"], out["orphans_after"]
    lines = [f"orphans: {sum(b.values())} before, {sum(a.values())} after"]
    lines += [f"  {k}: {b[k]} -> {a[k]}" for k in sorted(b | a, key=lambda k: -b[k])]
    lines.append("files changed: " + (", ".join(f"{k} {n}" for k, n in
                                                 sorted(out["changed"].items())) or "none"))
    pairs = out.get("domain_hubs", [])
    lines.append(f"study domains joined to topic hubs: {len(pairs)} pairs")
    lines += [f"  [[{d}]] <-> [[{h}]]" for d, h in pairs]
    rows = out["unresolved"]
    by = Counter()
    for r in rows:
        by[r["class"]] += r["count"]
    lines.append(f"unresolved links: {sum(by.values())} in {len(rows)} targets ("
                 + ", ".join(f"{k} {by[k]}" for k in ("near", "missing", "junk")) + ")")
    for r in rows:
        to = f" -> [[{r['to']}]]" if r["to"] else ""
        left = r["count"] - r["fixed"]
        lines.append(f"  {r['class']:<7} {r['count']:>3}  [[{r['target']}]]{to}  "
                     f"e.g. {r['example']}" + (f"  ({left} left)" if left and
                                                r["class"] != "missing" else ""))
    return lines
